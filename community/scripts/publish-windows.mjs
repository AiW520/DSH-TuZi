import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, basename, join } from 'node:path';
import assert from 'node:assert/strict';

const repository = 'AiW520/DSH-TuZi';
const runId = process.env.QUALIFICATION_RUN_ID;
const tag = process.env.COMMUNITY_RELEASE_TAG;
assert.match(runId || '', /^\d+$/);
assert.match(tag || '', /^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?-community\.\d+$/);
const gh = args => execFileSync('gh', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }).trim();
const run = JSON.parse(gh(['api', `repos/${repository}/actions/runs/${runId}`]));
assert.equal(run.conclusion, 'success');
assert.equal(run.path, '.github/workflows/community-build.yml');
assert.equal(run.head_branch, 'main');
assert.equal(run.head_repository.full_name, repository);
const directory = resolve('qualified-windows');
gh(['run', 'download', runId, '--repo', repository, '--name', 'dsh-tuzi-windows-x64-qualified', '--dir', directory]);
const read = async name => JSON.parse((await readFile(join(directory, name), 'utf8')).replace(/^\uFEFF/, ''));
const record = await read('qualification.json');
assert.equal(record.schemaVersion, 1);
assert.equal(`v${record.communityVersion}`, tag, 'Release tag must match the installed community identity');
assert.equal(record.qualified, true);
assert.equal(record.sourceCommit, run.head_sha);
assert.equal(record.runId, runId);
assert.equal(record.platform, 'Windows');
assert.equal(record.arch, 'x64');
assert.equal(record.signing, 'unsigned-test');
assert.equal(basename(record.artifact), record.artifact);
assert.match(record.artifact, /^dsh-tuzi-[\w.-]+-unsigned\.exe$/);
for (const test of ['NSIS silent installation', 'installed Harness sessions and task states', 'installed desktop pet interactions', 'uninstall preserves community home', 'installed update notifications']) assert(record.tests.includes(test), `Missing qualification: ${test}`);
const installer = join(directory, record.artifact);
const appVersion = record.artifact.match(/^dsh-tuzi-(.+)-win-x64-unsigned\.exe$/)?.[1];
assert(appVersion);
const previewNumber = tag.match(/community\.(\d+)$/)[1];
assert.equal(tag, `v${appVersion}-community.${previewNumber}`);
const bytes = await readFile(installer);
assert.equal(bytes.subarray(0, 2).toString(), 'MZ');
assert.equal(bytes.length, record.bytes);
assert.equal(createHash('sha256').update(bytes).digest('hex'), record.sha256);
const checksum = join(directory, 'SHA256SUMS.txt');
await writeFile(checksum, `${record.sha256}  ${record.artifact}\n`);
const notes = join(directory, 'RELEASE-NOTES.md');
await writeFile(notes, `DSH-TuZi 社区版 Windows x64 预览包，包含独立悬浮云朵兔。\n\n- 更新仅提醒，自动下载与安装关闭；启动后及每 6 小时检查，支持手动检查、24 小时后提醒和忽略本版。\n- 云朵兔支持自然眨眼、点击轻跳、右键互动、减少动作及 Harness 任务反馈。\n- Windows 安装界面采用社区版名称与图标；卸载保留社区数据目录。\n\n验收：GitHub 原生 Windows runner 上完成 NSIS 安装、安装后的 Harness 会话与工具执行、桌宠互动、卸载保留数据。模型响应来自本地测试服务，本次没有重复线上供应商测试。\n\n适用 Windows x64（Intel / AMD）；Windows ARM64 尚未验收。未签名预览版，Windows 可能提示未知发布者，自动更新关闭。\n\n构建与验收：${run.html_url}\n源提交：\`${record.sourceCommit}\`。社区发布标识：\`${tag}\`；安装包内含完整社区版本标识；内部基础版本为 \`${appVersion}\`。\n\n文件大小：${record.bytes} 字节。SHA-256：\`${record.sha256}\`。\n\nmacOS 用户通过下载页获取已验收的 Apple Silicon 包：https://aiw520.github.io/DSH-TuZi/#download\n\n已知检查记录：本地文档检查 42 项通过、1 项已有误报（python/sdk/uv.lock 数字被识别为提交哈希）。\n`);
gh(['release', 'create', tag, '--repo', repository, '--target', record.sourceCommit, '--draft', '--prerelease', '--title', `DSH-TuZi 社区预览版 ${previewNumber} · Windows x64 与云朵兔`, '--notes-file', notes, installer, checksum, join(directory, 'qualification.json')]);
const releases = JSON.parse(gh(['api', `repos/${repository}/releases`]));
const release = releases.find(item => item.tag_name === tag);
assert(release?.draft);
const asset = release.assets.find(item => item.name === record.artifact);
assert.equal(asset.state, 'uploaded');
assert.equal(asset.size, record.bytes);
assert.equal(asset.digest, `sha256:${record.sha256}`);
gh(['release', 'edit', tag, '--repo', repository, '--draft=false', '--prerelease']);
console.log(`Published verified Windows installer: ${repository} ${tag}`);
